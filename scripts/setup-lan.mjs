import { readFileSync, writeFileSync } from 'node:fs';
import { parseEnv } from 'node:util';
import { isIP } from 'node:net';
import { fileURLToPath } from 'node:url';

const ip = process.argv[2];
const parts = ip?.split('.').map(Number) ?? [];
if (isIP(ip ?? '') !== 4 || !(parts[0] === 10 || (parts[0] === 172 && parts[1] >= 16 && parts[1] <= 31) || (parts[0] === 192 && parts[1] === 168))) {
  console.error('用法：npm run lan:setup -- <本机局域网IPv4>，例如 192.168.1.20；仅接受 RFC1918 私有地址。');
  process.exit(1);
}
const root = fileURLToPath(new URL('../', import.meta.url));
let env;
try { env = parseEnv(readFileSync(`${root}/.env`, 'utf8')); }
catch { console.error('请先复制 .env.example 为 .env，并配置 LiveKit Key/Secret。'); process.exit(1); }
if (!env.LIVEKIT_API_KEY || !env.LIVEKIT_API_SECRET || env.LIVEKIT_API_SECRET.length < 32) {
  console.error('.env 中需要 LIVEKIT_API_KEY 和至少 32 字符的 LIVEKIT_API_SECRET。'); process.exit(1);
}
writeFileSync(`${root}/.env.lan`, `# Generated by lan:setup. Re-run when the host LAN IP changes.\nLAN_IP=${ip}\nLIVEKIT_URL=ws://${ip}:5173/livekit\nTOKEN_ALLOWED_ORIGINS=http://${ip}:5173\n`);
writeFileSync(`${root}/deploy/livekit.lan.yaml`, `# Generated local configuration; do not commit credentials.\nport: 7880\nbind_addresses: ["0.0.0.0"]\nrtc:\n  tcp_port: 7881\n  udp_port: 7882\n  use_external_ip: false\n  node_ip: ${ip}\nkeys:\n  ${JSON.stringify(env.LIVEKIT_API_KEY)}: ${JSON.stringify(env.LIVEKIT_API_SECRET)}\n`);
console.log(`已生成局域网 HTTP 配置，页面地址：http://${ip}:5173\n跨机器麦克风测试需按 deploy/LAN.md 配置浏览器开发例外，然后运行局域网启动命令。`);
