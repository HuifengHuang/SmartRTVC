CREATE TABLE IF NOT EXISTS app_user (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, username VARCHAR(32) NOT NULL UNIQUE,
 password_hash VARCHAR(100) NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS call_session (
 id VARCHAR(36) PRIMARY KEY, caller_id BIGINT NOT NULL, callee_id BIGINT NOT NULL,
 room_name VARCHAR(64) NOT NULL UNIQUE, state VARCHAR(20) NOT NULL,
 caller_connected BOOLEAN NOT NULL DEFAULT FALSE, callee_connected BOOLEAN NOT NULL DEFAULT FALSE,
 end_reason VARCHAR(20), created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 accepted_at TIMESTAMP NULL, active_at TIMESTAMP NULL, ended_at TIMESTAMP NULL,
 FOREIGN KEY(caller_id) REFERENCES app_user(id), FOREIGN KEY(callee_id) REFERENCES app_user(id)
);
CREATE TABLE IF NOT EXISTS user_call (
 user_id BIGINT PRIMARY KEY, call_id VARCHAR(36) NOT NULL,
 FOREIGN KEY(user_id) REFERENCES app_user(id), FOREIGN KEY(call_id) REFERENCES call_session(id)
);
